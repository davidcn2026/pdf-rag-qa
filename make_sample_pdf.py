"""生成一份中文测试 PDF（sample.pdf），用于练习 RAG"""
from fpdf import FPDF

pdf = FPDF()
pdf.add_font("SimHei", "", "C:/Windows/Fonts/simhei.ttf")  # 注册黑体中文字体
pdf.add_page()
pdf.set_font("SimHei", size=14)
pdf.cell(0, 10, "人工智能基础入门", ln=1, align="C")
pdf.ln(4)
pdf.set_font("SimHei", size=11)

sections = [
    ("一、什么是人工智能", "人工智能（Artificial Intelligence，简称 AI）是计算机科学的一个分支，"
     "旨在研究如何让计算机模拟、延伸和扩展人类的智能。人工智能系统能够执行通常需要人类智能才能完成的任务，"
     "例如理解语言、识别图像、做出决策等。"),
    ("二、机器学习", "机器学习是人工智能的核心方法，它让计算机从数据中自动学习规律，"
     "而不是依靠人工编写规则。根据学习方式的不同，机器学习主要分为监督学习、无监督学习和强化学习三大类。"
     "监督学习使用带标签的数据进行训练，无监督学习在无标签数据中寻找隐藏的结构。"),
    ("三、深度学习与神经网络", "深度学习是机器学习的一个子领域，它通过多层神经网络来学习数据的特征表示，"
     "在图像识别、自然语言处理等领域取得了突破性进展。神经网络由多层神经元组成，包括输入层、隐藏层和输出层。"
     "训练神经网络的过程，就是不断调整权重参数，使模型的预测结果更接近真实值。"),
    ("四、过拟合", "过拟合是指模型在训练数据上表现很好，但在未见过的数据上表现很差的现象。"
     "过拟合的本质是模型过度记忆了训练数据中的噪声，而没有学到真正的规律。"
     "防止过拟合的常用方法包括增加训练数据、使用正则化技术以及提前停止训练。"),
    ("五、梯度下降", "梯度下降是一种常用的优化算法，它通过计算损失函数对参数的梯度，"
     "沿着梯度的反方向逐步更新参数，从而使损失值逐渐减小。学习率是梯度下降中的一个重要超参数，"
     "它决定了每次更新参数时迈出的步长大小。"),
    ("六、向量检索与 RAG", "向量检索是检索增强生成（简称 RAG）的核心技术，它把文本转换成向量，"
     "通过计算向量之间的相似度来找到语义相关的内容。RAG 系统在回答问题时，"
     "先从文档库中检索出与问题最相关的片段，再将这些片段作为上下文提供给大语言模型，"
     "从而使模型能够基于真实的文档内容回答问题，有效减少幻觉现象。"),
]

for title, body in sections:
    pdf.set_font("SimHei", size=12)
    pdf.cell(0, 8, title, ln=1)
    pdf.set_font("SimHei", size=11)
    pdf.multi_cell(0, 7, body)
    pdf.ln(4)

pdf.output("sample.pdf")
print("已生成 sample.pdf")
